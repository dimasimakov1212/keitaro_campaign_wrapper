#!/bin/bash

echo "🚀 Запускаем бэкенд (Docker) в фоновом режиме..."
docker compose up -d

# Небольшая пауза, чтобы Docker успел инициализировать сеть
sleep 2

echo "⚡ Запускаем фронтенд (Vite)..."
echo "Для остановки всего приложения нажмите Ctrl+C, а затем выполните './stop.sh'"
echo "-------------------------------------------------------------------"

# Переходим в папку frontend
cd frontend

# Автоматическая установка зависимостей, если node_modules отсутствует
if [ ! -d "node_modules" ]; then
    echo "📦 Установка npm-зависимостей (первый запуск)..."
    npm install
fi

# Запускаем dev-сервер
npm run dev